export function detectDistricts(text: string): string[] {
  const haystack = text.toLowerCase();
  const found = new Set<string>();

  for (const district of DISTRICTS) {
    const full = district.toLowerCase();
    const stem = full.replace(/ский$|ный$/, "");
    if (haystack.includes(full) || (stem.length >= 6 && haystack.includes(stem))) {
      found.add(district);
    }
  }

  for (const [alias, district] of Object.entries(ALIASES)) {
    if (haystack.includes(alias)) {
      found.add(district);
    }
  }

  return [...found];
}

export function matchDistrictQuery(query: string): string[] {
  return detectDistricts(query);
}
